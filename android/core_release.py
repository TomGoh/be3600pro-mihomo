#!/usr/bin/env python3
"""Bind generated Android metadata and packaged assets to the public core release."""
import hashlib
import json
import pathlib
import re
import shutil
import struct
import sys
import zipfile

ARCHIVE_ASSET = 'mihomo-router-armv7.gz'
PATCH_ASSET = 'mihomo-v1.19.32-udp-reply-candidate.patch'


def metadata(path):
    value = json.loads(pathlib.Path(path).read_text(encoding='utf-8'))
    if value.get('schema') != 1:
        raise ValueError('Unsupported core release schema')
    for name in ('archiveBytes', 'sourcePatchBytes'):
        if type(value.get(name)) is not int or value[name] <= 0:
            raise ValueError('Invalid release length: ' + name)
    for name in ('archiveSha256', 'sourcePatchSha256'):
        if not re.fullmatch('[0-9a-f]{64}', value.get(name, '')):
            raise ValueError('Invalid release hash: ' + name)
    if not re.fullmatch('[0-9a-f]{40}', value.get('upstreamCommit', '')):
        raise ValueError('Invalid upstream source commit')
    if not re.fullmatch('[A-Za-z0-9.+_-]{1,100}', value.get('version', '')):
        raise ValueError('Invalid release version')
    return value


def checked_file(path, length, digest):
    total = 0
    h = hashlib.sha256()
    with pathlib.Path(path).open('rb') as f:
        while True:
            chunk = f.read(131072)
            if not chunk:
                break
            total += len(chunk)
            h.update(chunk)
    if total != length or h.hexdigest() != digest:
        raise ValueError('Release asset length/hash mismatch: ' + str(path))


def generate(manifest, archive, patch, assets, generated):
    m = metadata(manifest)
    checked_file(archive, m['archiveBytes'], m['archiveSha256'])
    checked_file(patch, m['sourcePatchBytes'], m['sourcePatchSha256'])
    assets = pathlib.Path(assets)
    assets.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(archive, assets / ARCHIVE_ASSET)
    shutil.copyfile(patch, assets / PATCH_ASSET)
    shutil.copyfile(manifest, assets / 'core-release.json')
    display = m['version'].split('-udpfix', 1)[0] + ' + UDP \u4fee\u590d\u6d4b\u8bd5\u7248'
    constants = {
        'VERSION': m['version'], 'DISPLAY_VERSION': display,
        'ARCHIVE_ASSET': ARCHIVE_ASSET, 'ARCHIVE_SHA256': m['archiveSha256'],
        'PATCH_ASSET': PATCH_ASSET, 'PATCH_SHA256': m['sourcePatchSha256'],
        'SOURCE_COMMIT': m['upstreamCommit'],
    }
    code = ['package dev.jose.routerproxy;', '', '// Generated by android/core_release.py from release/core-release.json.', 'final class CoreRelease {']
    for name, value in constants.items():
        code.append(' static final String %s=%s;' % (name, json.dumps(value, ensure_ascii=True)))
    code += [' static final long ARCHIVE_BYTES=%dL;' % m['archiveBytes'], ' private CoreRelease() {}', '}']
    target = pathlib.Path(generated) / 'dev/jose/routerproxy/CoreRelease.java'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text('\n'.join(code) + '\n', encoding='utf-8')
    source = ('Mihomo modified release: %s\nLicense: GNU GPL version 3 (see LICENSE-mihomo.txt)\n'
              'Upstream source commit: %s\nSource: https://github.com/MetaCubeX/mihomo/tree/%s\n'
              'Complete local source modifications relative to that commit: %s (bundled asset)\n'
              'Patch SHA-256: %s\nApply to upstream source: git apply %s\n'
              'Build toolchain: %s; target Linux ARMv7.\n'
              'Modifications: UDP transparent reply path with IPv4 IP_PKTINFO and IPv6 packet handling; '
              'the bundled patch includes the source changes and tests.\n'
              'No user pairing, subscription or router configuration is included.\n') % (
                  m['version'], m['upstreamCommit'], m['upstreamCommit'], PATCH_ASSET,
                  m['sourcePatchSha256'], PATCH_ASSET, m.get('goVersion', 'see release metadata'))
    (assets / 'CORE-SOURCE.txt').write_text(source, encoding='utf-8')
    print('PASS: release core and source patch match public manifest; generated CoreRelease.java')


def verify_apk(manifest, apk):
    m = metadata(manifest)
    with zipfile.ZipFile(apk) as z:
        if z.read('assets/core-release.json') != pathlib.Path(manifest).read_bytes():
            raise ValueError('Packaged release manifest differs')
        for name, prefix in ((ARCHIVE_ASSET, 'archive'), (PATCH_ASSET, 'sourcePatch')):
            data = z.read('assets/' + name)
            if len(data) != m[prefix + 'Bytes'] or hashlib.sha256(data).hexdigest() != m[prefix + 'Sha256']:
                raise ValueError('Packaged release asset differs: ' + name)
        info = z.getinfo('resources.arsc')
        with open(apk, 'rb') as f:
            f.seek(info.header_offset)
            header = f.read(30)
        name_length, extra_length = struct.unpack_from('<HH', header, 26)
        offset = info.header_offset + 30 + name_length + extra_length
        if info.compress_type != zipfile.ZIP_STORED or offset % 4:
            raise ValueError('resources.arsc must be ZIP_STORED and 4-byte aligned')
        for name in ('assets/LICENSE-mihomo.txt', 'assets/NOTICE.txt', 'assets/CORE-SOURCE.txt'):
            if not z.read(name):
                raise ValueError('Missing license/source notice')
        if z.testzip() is not None:
            raise ValueError('APK CRC failure')
        if any(name.endswith('.jks') or '/private/' in name or '/pairing' in name.lower() for name in z.namelist()):
            raise ValueError('Private asset in APK')
    print('PASS: final APK release manifest/core/patch bytes+hashes, GPL/source notices and ZIP CRC')
    print('PASS: resources.arsc ZIP_STORED, data offset %d (mod4=0)' % offset)


if __name__ == '__main__':
    if sys.argv[1] == 'generate':
        generate(*sys.argv[2:])
    elif sys.argv[1] == 'verify-apk':
        verify_apk(*sys.argv[2:])
    else:
        raise SystemExit('Expected generate or verify-apk')
